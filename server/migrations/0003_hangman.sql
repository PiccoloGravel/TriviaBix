-- Speed hangman phrases. Only A-Z letters are hidden on the board, so keep phrases ASCII;
-- digits and punctuation show from the start.
CREATE TABLE hangman_phrases (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    category    TEXT    NOT NULL,
    phrase      TEXT    NOT NULL,
    rating      TEXT    NOT NULL DEFAULT 'PG' CHECK (rating IN ('PG', 'PG-13', 'MA', 'NC-17')),
    source      TEXT    NOT NULL DEFAULT 'seed',
    created_at  TEXT    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX hangman_phrases_phrase ON hangman_phrases(phrase);

