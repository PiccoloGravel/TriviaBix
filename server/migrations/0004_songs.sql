-- Songs for the Name That Tune mode. We store only the title and artist; the audio is a
-- 30-second preview streamed from the iTunes Search API at play time. `itunes_id` and the
-- other track columns are filled in the first time a song is looked up.
CREATE TABLE songs (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    title       TEXT    NOT NULL,
    artist      TEXT    NOT NULL,
    year        INTEGER NOT NULL,
    rating      TEXT    NOT NULL DEFAULT 'PG' CHECK (rating IN ('PG', 'PG-13', 'MA', 'NC-17')),
    itunes_id   INTEGER,
    explicit    INTEGER NOT NULL DEFAULT 0,
    artwork_url TEXT,
    store_url   TEXT,
    -- Set when the music service has no playable preview, so we stop asking.
    unplayable  INTEGER NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX songs_title_artist ON songs(title, artist);

